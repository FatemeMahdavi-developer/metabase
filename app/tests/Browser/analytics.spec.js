test('notebook filters aggregate results and summarizes them in another stage', async ({ page }) => {
    await login(page); let reportId;
    try {
        await newReport(page, 'sales_overview');
        await page.locator('[data-action=addMetric]').click(); await page.locator('[data-function=sum]').click(); await editorModal(page).locator('[name=field]').selectOption('total'); await editorModal(page).locator('[name=label]').fill('فروش'); await page.locator('[data-action=saveMetric]').click();
        await page.locator('[data-action=addDimension]').click(); await editorModal(page).locator('[name=field]').selectOption('city'); await page.locator('[data-action=saveDimension]').click();
        await expect(editorModal(page)).toHaveCount(0);
        const definition = await page.evaluate(() => window.analyticsStudio.report.query_definition); const original = await api(page, 'reports/preview', 'POST', { query_definition: definition }); const metric = definition.metrics[0].key;
        expect(original.rows.length).toBeGreaterThan(2);
        const ordered = original.rows.map(row => row[metric]).sort((a, b) => a - b); const threshold = ordered[2]; const expected = ordered.filter(value => value >= threshold); const average = expected.reduce((sum, value) => sum + value, 0) / expected.length;
        await page.locator('[data-action=addNotebookStep]').click(); await editorModal(page).locator('[data-action=addStage]').click();
        await page.locator('[data-action=addStageFilter]').click(); await editorModal(page).locator('[name=filter_value_0]').fill(String(threshold)); await page.locator('[data-action=saveStage]').click(); await expect(editorModal(page)).toHaveCount(0);
        await expect(page.locator('.mb-stage-after')).toHaveCount(1);
        await page.locator('[data-action=addNotebookStep]').click(); await editorModal(page).locator('[data-action=addStage]').click();
        await editorModal(page).locator('[name=mode]').selectOption('aggregate'); await editorModal(page).locator('[name=metric_function_0]').selectOption('avg'); await editorModal(page).locator('[name=metric_field_0]').selectOption(metric); await editorModal(page).locator('[name=metric_label_0]').fill('میانگین فروش شهر'); await page.locator('[data-action=saveStage]').click(); await expect(editorModal(page)).toHaveCount(0);
        await expect(page.locator('.mb-stage-after')).toHaveCount(2);
        await page.screenshot({ path: 'tests/Browser/artifacts/notebook-stages.png', fullPage: true });
        await page.getByRole('button', { name: 'نمایش نتیجه', exact: true }).click(); await expect(page.locator('.mb-stat-value')).toBeVisible();
        const result = await page.evaluate(() => window.analyticsStudio.previewResult); expect(result.rows).toHaveLength(1); expect(Object.values(result.rows[0])[0]).toBeCloseTo(average, 2);
        await page.locator('[data-action=reportSaveDialog]').click(); await editorModal(page).locator('[name=name]').fill('Stages browser test ' + Date.now()); await page.locator('[data-action=saveReport]').click(); await expect(editorModal(page)).toHaveCount(0); reportId = await page.evaluate(() => window.analyticsStudio.report.id);
        const saved = (await api(page, 'library')).reports.find(row => row.id === reportId); expect(saved.query_definition.stages).toHaveLength(2);
    } finally { if (reportId) await api(page, `reports/${reportId}`, 'DELETE'); }
});

test('join and custom expression after summarizing a question persist with correct results', async ({ page }) => {
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await login(page); let reportId, dashboardId;
    try {
        await newReport(page, 'orders');
        await page.locator('[data-action=addMetric]').click();
        await page.locator('[data-function=sum]').click();
        await editorModal(page).locator('[name=field]').selectOption('total');
        await editorModal(page).locator('[name=label]').fill('فروش هر مشتری');
        await page.locator('[data-action=saveMetric]').click();
        await page.locator('[data-action=addDimension]').click();
        await editorModal(page).locator('[name=field]').selectOption('customer_id');
        await page.locator('[data-action=saveDimension]').click();
        const definition = await page.evaluate(() => window.analyticsStudio.report.query_definition);
        const metric = definition.metrics[0].key;
        const oracle = await api(page, 'reports/preview', 'POST', { query_definition: { ...definition, mode: 'native', metrics: [], dimensions: [], sql: "SELECT o.customer_id, SUM(o.total) AS sales FROM orders o INNER JOIN customers c ON o.customer_id = c.id WHERE c.city = 'تهران' GROUP BY o.customer_id", parameters: [] } });
        expect(oracle.rows.length).toBeGreaterThan(0);
        await page.locator('[data-action=addNotebookStep]').click();
        await editorModal(page).locator('[data-action=addStage]').click();
        await page.locator('[data-action=addStageJoin]').click();
        await editorModal(page).locator('[name=source]').selectOption('customers');
        await page.locator('[data-action=chooseJoinType][data-type=inner]').click();
        await editorModal(page).locator('[name=left_0]').selectOption('customer_id');
        await editorModal(page).locator('[name=right_0]').selectOption('id');
        await page.locator('[data-action=saveJoin]').click();
        await expect(page.locator('[data-action=saveStage]')).toBeVisible();
        const alias = await page.evaluate(() => window.analyticsStudio.stageDraft.joins[0].alias);
        await page.locator('[data-action=addStageExpression]').click();
        await editorModal(page).locator('[name=label]').fill('مالیات فروش');
        await editorModal(page).locator('[name=expression]').fill(`[${metric}] * 0.1`);
        await page.locator('[data-action=saveExpression]').click();
        await expect(page.locator('[data-action=saveStage]')).toBeVisible();
        const expression = await page.evaluate(() => window.analyticsStudio.stageDraft.expressions[0].key);
        await page.locator('[data-action=addStageFilter]').click();
        await editorModal(page).locator('[name=filter_field_0]').selectOption(alias + '.city');
        await editorModal(page).locator('[name=filter_operator_0]').selectOption('eq');
        await editorModal(page).locator('[name=filter_value_0]').fill('تهران');
        await expect(editorModal(page).locator('.fi-modal-footer')).toBeInViewport({ ratio: 1 });
        await page.screenshot({ path: 'tests/Browser/artifacts/stage-join-form.png', fullPage: true });
        await page.locator('[data-action=saveStage]').click();
        await expect(editorModal(page)).toHaveCount(0);
        await expect(page.locator('.mb-stage-after')).toContainText('INNER JOIN');
        await page.getByRole('button', { name: 'نمایش نتیجه', exact: true }).click();
        await expect.poll(() => page.evaluate(() => !!window.analyticsStudio.previewResult)).toBe(true);
        const result = await page.evaluate(() => window.analyticsStudio.previewResult);
        expect(result.rows).toHaveLength(oracle.rows.length);
        for (const row of result.rows) {
            const expected = oracle.rows.find(item => item.customer_id === row.customer_id);
            expect(row[metric]).toBeCloseTo(expected.sales, 2);
            expect(row[expression]).toBeCloseTo(expected.sales * 0.1, 2);
            expect(row[alias + '.city']).toBe('تهران');
        }
        await page.locator('[data-action=displayPicker]').click();
        await page.locator('[data-display=table]').click();
        await expect(page.locator('.mb-preview .mb-table')).toBeVisible();
        await page.screenshot({ path: 'tests/Browser/artifacts/stage-join-result.png', fullPage: true });
        await page.locator('[data-action=reportSaveDialog]').click();
        const reportName = 'Stage join browser test ' + Date.now();
        await editorModal(page).locator('[name=name]').fill(reportName);
        await page.locator('[data-action=saveReport]').click();
        await expect(editorModal(page)).toHaveCount(0);
        reportId = await page.evaluate(() => window.analyticsStudio.report.id);
        const saved = (await api(page, 'library')).reports.find(row => row.id === reportId);
        expect(saved.query_definition.stages[0].joins[0].type).toBe('inner');
        expect(saved.query_definition.stages[0].expressions[0].type).toBe('number');
        expect(saved.query_definition.stages[0].filters[0].field).toBe(alias + '.city');
        dashboardId = await createDashboard(page, 'Stage join dashboard ' + Date.now());
        await page.locator('[data-action=addReportCard]').click();
        await editorModal(page).locator('[data-action=pickReport]').filter({ hasText: reportName }).click();
        await closePicker(page);
        await expect(page.locator('.mb-card .mb-table')).toBeVisible();
        await page.locator('[data-action=addDashboardFilter]').click();
        await page.locator('[data-action=chooseDashboardFilter][data-type=text]').click();
        await editorModal(page).locator('[name=label]').fill('شهر مشتری در مرحلهٔ بعد');
        await page.locator('[data-action=mapDashboardFilter]').click();
        await page.locator('[data-card-filter-binding]').selectOption('stage:0:' + alias + '.city');
        await page.screenshot({ path: 'tests/Browser/artifacts/stage-dashboard-mapping.png', fullPage: true });
        await page.locator('[data-action=finishFilterMapping]').click();
        await page.locator('[data-action=saveDashboard]').click();
        await expect(page.locator('.mb-editbar')).toHaveCount(0);
        await page.locator('[data-action=editFilterValue]').click();
        await editorModal(page).locator('.mb-value-option').filter({ hasText: /^تهران$/ }).locator('input[name=values]').check();
        await page.locator('[data-action=saveFilterValue]').click();
        await expect(page.locator('.mb-card .mb-loading')).toHaveCount(0);
        const board = await api(page, `dashboards/${dashboardId}`);
        expect(board.filters[0].bindings[0].target).toBe('stage:0:' + alias + '.city');
        const filtered = await api(page, `dashboards/${dashboardId}/widgets/${board.widgets[0].key}/query`, 'POST', { parameters: { [board.filters[0].key]: 'تهران' } });
        expect(filtered.rows).toHaveLength(oracle.rows.length);
        expect(filtered.rows.every(row => row[alias + '.city'] === 'تهران')).toBe(true);
        expect(errors).toEqual([]);
    } finally { if (dashboardId) await api(page, `dashboards/${dashboardId}`, 'DELETE'); if (reportId) await api(page, `reports/${reportId}`, 'DELETE'); }
});
